import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { validateSuite } from './lib/conformance.mjs';

const root = new URL('../', import.meta.url);
const path = (name) => new URL(name, root);
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const sync = process.argv.includes('--sync');
const sourceIndex = process.argv.indexOf('--source');
const source = sourceIndex < 0 ? undefined : resolve(process.argv[sourceIndex + 1]);
if (sync && !source) throw new Error('--sync requires --source PATH');
if (sync) {
  const suiteBytes = readFileSync(`${source}/test-vectors/oris-001/suite.json`);
  validateSuite(JSON.parse(suiteBytes));
  const revision = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: source, encoding: 'utf8' });
  if (revision.status !== 0) throw new Error('could not identify Standards base revision');
  const files = ['rfcs/ORIS-001.md', 'test-vectors/oris-001/suite.json', 'scripts/noms/generate_vectors.py'];
  const clean = files.every((name) => spawnSync('git', ['ls-files', '--error-unmatch', name], { cwd: source }).status === 0)
    && spawnSync('git', ['diff', 'HEAD', '--quiet', '--', ...files], { cwd: source }).status === 0;
  const manifest = {
    schema_version: 1,
    standards_repository: 'OpenRai/Standards',
    source_revision: clean ? revision.stdout.trim() : null,
    base_revision: revision.stdout.trim(),
    spec_sha256: sha256(readFileSync(`${source}/rfcs/ORIS-001.md`)),
    generator_sha256: sha256(readFileSync(`${source}/scripts/noms/generate_vectors.py`)),
    suite_sha256: sha256(suiteBytes),
    case_count: JSON.parse(suiteBytes).cases.length,
  };
  writeFileSync(path('conformance/suite.json'), suiteBytes);
  writeFileSync(path('conformance/manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
}
const suiteBytes = readFileSync(path('conformance/suite.json'));
const suite = validateSuite(JSON.parse(suiteBytes));
const manifest = JSON.parse(readFileSync(path('conformance/manifest.json')));
if (manifest.schema_version !== 1 || manifest.suite_sha256 !== sha256(suiteBytes) || manifest.case_count !== suite.cases.length) throw new Error('fixture manifest mismatch');
if (source) {
  for (const [name, expected] of [
    ['rfcs/ORIS-001.md', manifest.spec_sha256],
    ['scripts/noms/generate_vectors.py', manifest.generator_sha256],
    ['test-vectors/oris-001/suite.json', manifest.suite_sha256],
  ]) if (sha256(readFileSync(`${source}/${name}`)) !== expected) throw new Error(`Standards source drift: ${name}`);
}
if (process.argv.includes('--release')) {
  if (!/^[a-f0-9]{40}$/.test(manifest.source_revision ?? '')) throw new Error('Release blocked: commit the Standards changes, then resync fixtures to a committed revision');
  for (const [name, expected] of [
    ['rfcs/ORIS-001.md', manifest.spec_sha256],
    ['scripts/noms/generate_vectors.py', manifest.generator_sha256],
    ['test-vectors/oris-001/suite.json', manifest.suite_sha256],
  ]) {
    const result = spawnSync('gh', ['api', `repos/OpenRai/Standards/contents/${name}?ref=${manifest.source_revision}`, '--jq', '.content'], { encoding: 'utf8' });
    if (result.status !== 0 || sha256(Buffer.from(result.stdout, 'base64')) !== expected) throw new Error(`Published Standards source mismatch: ${name}`);
  }
}

const find = (id) => suite.cases.find((test) => test.id === id);
const key = find('key-0');
const first = find('sign-0-1');
const empty = find('sign-0-0');
const values = {
  TEST_PRIVATE_KEY: key.input.private_key,
  TEST_ACCOUNT: key.expected.account,
  TEST_MESSAGE: first.input.message,
  TEST_SIGNATURE: first.expected.signature,
  EMPTY_SIGNATURE: empty.expected.signature,
  EMPTY_DIGEST: find('message-0').expected.digest,
  NONCANONICAL_SIGNATURE: find('s-plus-L').input.signature,
};
const ts = '// Generated by scripts/check-fixtures.mjs from the canonical suite.\n' + Object.entries(values).map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`).join('\n') + '\n';
const rust = '// Generated by scripts/check-fixtures.mjs from the canonical suite.\n' + Object.entries(values).map(([name, value]) => `#[rustfmt::skip]\npub const ${name}: &str = ${JSON.stringify(value)};`).join('\n') + '\n';
const vectors = {
  oris_revision: manifest.source_revision ? `OpenRai/Standards@${manifest.source_revision}` : `ORIS-001 sha256:${manifest.spec_sha256}`,
  source: 'https://github.com/OpenRai/Standards/tree/main/test-vectors/oris-001',
  keypair: { private_key: key.input.private_key, public_key: key.expected.public_key, account: key.expected.account },
  vectors: [['unicode-emoji', 1], ['empty', 0]].map(([name, n]) => ({ name, message: find(`sign-0-${n}`).input.message, message_utf8_hex: find(`message-${n}`).expected.message_utf8_hex, payload_hex: find(`message-${n}`).expected.payload_hex, digest: find(`message-${n}`).expected.digest, signature: find(`sign-0-${n}`).expected.signature })),
};
for (const [name, data] of [
  ['packages/typescript/src/self-test-vectors.ts', ts],
  ['crates/noms-cli/src/self_test_vectors.rs', rust],
  ['conformance/vectors.json', JSON.stringify(vectors, null, 2) + '\n'],
  ['crates/noms/tests/data/suite.json', suiteBytes.toString('utf8')],
]) {
  if (sync) { mkdirSync(new URL('./', path(name)), { recursive: true }); writeFileSync(path(name), data); }
  else if (!existsSync(path(name)) || readFileSync(path(name), 'utf8') !== data) throw new Error(`Generated fixture drift: ${name}; resync from Standards`);
}
console.log(`Validated ${suite.cases.length} fixtures; suite ${manifest.suite_sha256}; Standards ${manifest.source_revision ?? 'working copy (content hashes pinned)'}`);
